def table(d, off):
    n = struct.unpack_from('<I', d, off)[0]
    return [(struct.unpack_from('<I', d, off + 4 + 4 * i)[0], d[off + 4 + 4 * n + 4 * i:off + 7 + 4 * n + 4 * i]) for i in range(n)]


def t32_textures(idd_path):
    """Every T32 record of a layout file as RGB (uint8), in file order."""
    d = open(idd_path, 'rb').read()
    tex = table(d, 0)[1][0]
    out = []
    for o, tag in table(d, tex):
        if tag != b'T32':
            continue
        h = tex + o
        ctw, cth = struct.unpack_from('<HH', d, h + 4)
        size = ctw * cth * 4
        payload, clut = d[h + 0xE0:h + 0xE0 + size], d[h + 0xE0 + size + 0x100:h + 0xE0 + size + 0x500]
        mem = bytearray(size)
        for y in range(cth):
            for x in range(ctw):
                a = ((y // 32) * (ctw // 64) * 32 + B32[(y % 32) // 8][(x % 64) // 8] + (x // 64) * 32) * 256 + C32[y % 8][x % 8] * 4
                mem[a:a + 4] = payload[(y * ctw + x) * 4:(y * ctw + x) * 4 + 4]
        w = 512 if size >= 0x40000 else 256
        hgt = size // w
        img = np.zeros((hgt, w, 3), np.uint8)
        for y in range(hgt):
            for x in range(w):
                k = mem[((y // 64) * (w // 128) + x // 128) * 32 * 256 + B32[(y % 64) // 16][(x % 128) // 16] * 256 + C8[y % 16][x % 16]]
                s = (k & 0xE7) | ((k & 8) << 1) | ((k & 0x10) >> 1)
                img[y, x] = tuple(clut[s * 4:s * 4 + 3])
        out.append(img)
    return out
